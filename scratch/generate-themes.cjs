let css = '';
for (const [theme, colors] of Object.entries(presets)) {
  const selector = theme === 'blue' ? ':root, :root.theme-blue' : `:root.theme-${theme}`;
  css += `${selector} {\n`;
  for (const [shade, hsl] of Object.entries(colors)) {
    css += `  --brand-${shade}: ${hsl};\n`;
  }
  css += '}\n\n';
}

const indexCss = fs.readFileSync('src/index.css', 'utf8');
const lines = indexCss.split('\n');
const header = lines.slice(0, 4).join('\n');
const restIndex = lines.findIndex((l, i) => i > 15 && l.includes('@layer base {'));
const rest = lines.slice(restIndex).join('\n');

fs.writeFileSync('src/index.css', header + '\n' + css + rest);
