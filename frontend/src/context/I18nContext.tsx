export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Language>('id');

  useEffect(() => {
    const saved = window.localStorage.getItem('language') as Language | null;
    if (saved && (saved === 'id' || saved === 'en')) {
      setLocaleState(saved);
    }
  }, []);

  const setLocale = (newLocale: Language) => {
    setLocaleState(newLocale);
    window.localStorage.setItem('language', newLocale);
  };

  const t = (key: string, variablesOrDefault?: string | Record<string, string | number>) => {
    let text = dictionaries[locale]?.[key] || dictionaries['id']?.[key];
    if (!text && typeof variablesOrDefault === 'string') {
        text = variablesOrDefault;
    } else if (!text) {
        text = key;
    }

    if (variablesOrDefault && typeof variablesOrDefault !== 'string') {
      Object.entries(variablesOrDefault).forEach(([k, v]) => {
        text = text.replace(new RegExp(`{${k}}`, 'g'), String(v));
      });
    }
    return text;
  };

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

